func main() {
	help := flag.Bool("help", false, "print usage")
	name := flag.String("name", "default", "vault name")
	cmd := flag.String("cmd", "create", "create|balance|version")
	flag.Parse()
	if *help {
		fmt.Fprintf(os.Stderr, "avaxc %s (%s)\n", version, "AVAX")
		flag.PrintDefaults()
		return
	}
	cfg := config.Default()
	svc := wallet.New(cfg)
	switch *cmd {
	case "version":
		fmt.Println(version)
	case "create":
		v := svc.Create(*name, "demo")
		fmt.Println(v.ID, v.Accounts[0].Address)
	case "balance":
		v := svc.Create(*name, "demo")
		fmt.Println(v.Total())
	default:
		fmt.Fprintln(os.Stderr, "unknown cmd")
		os.Exit(2)
	}
}
